/** Instante de referência fixo: a mesma fixture produz sempre o mesmo fingerprint. */
export const BASE_INSTANT = Date.parse('2026-09-10T09:00:00.000Z');

/** `ago(30)` = 30 minutos antes do instante de referência. */
export const ago = (minutes: number): string => new Date(BASE_INSTANT - minutes * 60_000).toISOString();

/** FNV-1a de 32 bits. Determinístico e suficiente para identificar conteúdo na UI. */
export function fingerprint(seed: string): string {
  let hash = 0x811c9dc5;
  for (let i = 0; i < seed.length; i++) {
    hash ^= seed.charCodeAt(i);
    hash = Math.imul(hash, 0x01000193) >>> 0;
  }
  return `FP-${hash.toString(16).toUpperCase().padStart(8, '0')}`;
}

